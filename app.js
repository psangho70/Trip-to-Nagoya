// 2.6.2 방문지 상세 페이지 닫기
function closePlaceDetail(scrollUp = true) {
  const listView = document.getElementById("places-list-view");
  const detailView = document.getElementById("places-detail-view");

  if (detailView && listView && detailView.style.display !== "none") {
    detailView.style.display = "none";
    listView.style.display = "block";
    if (scrollUp) {
      window.scrollTo({ top: 0, behavior: "smooth" });
    }
  }
}

