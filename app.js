// 2.5.1 Web Speech API 일본어 음성 합성 (TTS)
function speakJapanese(text, btnElement) {
  if (!('speechSynthesis' in window)) {
    alert("현재 브라우저에서 오디오 음성(SpeechSynthesis) 기능을 지원하지 않습니다.");
    return;
  }

  // 이전 재생 중인 음성 취소
  window.speechSynthesis.cancel();

  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = 'ja-JP';
  utterance.rate = 0.88; // 차량 안에서도 택시 기사님이 또박또박 명확하게 들을 수 있는 최적 속도
  utterance.pitch = 1.0;
  utterance.volume = 1.0;

  // 브라우저에 등록된 일본어 보이스 검색 및 지정
  const voices = window.speechSynthesis.getVoices();
  const jaVoice = voices.find(v => v.lang.startsWith('ja') || v.lang.includes('JP'));
  if (jaVoice) {
    utterance.voice = jaVoice;
  }

  // 재생 상태에 따른 UI 애니메이션 처리
  if (btnElement) {
    btnElement.classList.add('speaking');
    const originalHtml = btnElement.innerHTML;
    btnElement.innerHTML = `<span class="audio-icon pulse">🔊</span> <b>일본어 말하는 중...</b>`;

    utterance.onend = () => {
      btnElement.classList.remove('speaking');
      btnElement.innerHTML = originalHtml;
    };
    utterance.onerror = () => {
      btnElement.classList.remove('speaking');
      btnElement.innerHTML = originalHtml;
    };
  }

  showToast(`🔊 일본어 오디오 재생: "${text}"`);
  window.speechSynthesis.speak(utterance);
}

// 모바일 브라우저 음성 로드 이벤트 등록
